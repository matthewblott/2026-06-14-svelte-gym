<p><strong>Last updated:</strong> 2 August 2026</p>

<p>This Privacy Policy explains how Jimlog ("We", "Us", or "Our") handles information when You use the Jimlog application (the "Service").</p>

<h2>1. Overview</h2>

<p>Jimlog is designed to operate without requiring You to create an account or provide personal information.</p>

<p>You can use the core functionality of the Service without providing an email address or other contact information.</p>

<p>You may optionally provide an email address to create an account and access Your workout records on other devices.</p>

<h2>2. Information We Collect</h2>

<h3>Workout Data</h3>

<p>The Service allows You to record information about Your gym and fitness sessions.</p>

<p>For cardio sessions, We collect:</p>

<ul>
  <li>The duration of the session;</li>
  <li>The distance covered.</li>
</ul>

<p>For sessions involving weights, We collect:</p>

<ul>
  <li>The weight used;</li>
  <li>The number of repetitions.</li>
</ul>

<p>We do not collect health information from Apple Health or HealthKit, and We do not collect information such as heart rate, medical conditions, or body measurements.</p>

<h3>Device-Associated Account Identifier</h3>

<p>When You first use the Application, a technical account identifier is created and stored on Your Device. This identifier allows the Service to associate Your workout records with Your anonymous account.</p>

<p>This identifier:</p>

<ul>
  <li>Does not contain Your name or email address;</li>
  <li>Is used to associate Your workout records with Your anonymous account;</li>
  <li>Allows You to use the Service without creating an account.</li>
</ul>

<h3>Email Address</h3>

<p>If You choose to create an account, We collect the email address You provide.</p>

<p>Your email address is used solely to create and authenticate Your account and to allow You to access Your workout records on other devices.</p>

<p>When You create an account, the workout records associated with Your existing anonymous account are transferred to and associated with Your new account.</p>

<h3>Technical Data</h3>

<p>Basic technical information, such as IP address and standard web request logs, may be processed by our hosting provider for security, debugging, and operational purposes.</p>

<p>We do not use analytics services, tracking technologies, or advertising identifiers.</p>

<h2>3. How We Use Information</h2>

<p>We use information solely to:</p>

<ul>
  <li>Provide and maintain the Service;</li>
  <li>Store and retrieve Your workout records;</li>
  <li>Allow You to access Your workout records on multiple devices when You create an account;</li>
  <li>Maintain the security and integrity of the Service;</li>
  <li>Operate, troubleshoot, and improve the reliability of the Service.</li>
</ul>

<p>We do not use Your workout data or email address for advertising or marketing purposes.</p>

<h2>4. Data Sharing</h2>

<p>We do not sell, rent, or share Your data with advertisers or third parties for marketing purposes.</p>

<p>Your data is processed only as necessary to provide the Service, including through our hosting provider.</p>

<p>Our hosting provider may process technical information and stored workout data on our behalf in order to provide the infrastructure required to operate the Service.</p>

<h2>5. Data Retention</h2>

<p>Your workout records remain stored on our servers while Your anonymous account or registered account remains active.</p>

<p>If You use the Service without creating an account, Your records remain associated with Your anonymous device-associated account. If You delete the Application or clear its data, the identifier required to access those records may be lost and the records cannot be recovered through the Application.</p>

<p>If You create an account, Your workout records are associated with that account and remain stored until You delete Your account or We are otherwise required to delete them.</p>

<h2>6. Data Deletion</h2>

<p>You may delete Your account and all associated workout data through the Application.</p>

<p>This applies both to registered accounts and to anonymous accounts.</p>

<p>When You delete an account, We permanently delete the associated workout records and account information, except where We are legally required to retain certain information.</p>

<h2>7. Children's Privacy</h2>

<p>The Service is not directed to children under the age of 13. We do not knowingly collect personal information from children under 13.</p>

<p>If You believe that a child has provided personal information to Us, please contact Us using the details below.</p>

<h2>8. Security</h2>

<p>We take reasonable measures to protect stored data. However, no system is completely secure, and We cannot guarantee absolute security.</p>

<h2>9. Links to Other Websites</h2>

<p>The Service may contain links to third-party websites. We are not responsible for the privacy practices of those websites.</p>

<h2>10. Your Privacy Rights</h2>

<p>Depending on where You live and the applicable law, You may have rights in relation to Your personal data, including rights to access, correct, delete, or restrict the processing of Your personal data.</p>

<p>You can delete Your account and associated data directly through the Application. If You have a question about Your personal data or wish to exercise a privacy right that cannot be handled through the Application, You may contact Us using the details below.</p>

<h2>11. Changes to This Privacy Policy</h2>

<p>We may update this Privacy Policy from time to time. Any changes will be posted on this page and the "Last updated" date will be revised accordingly.</p>

<p>Continued use of the Service after changes become effective constitutes acceptance of the updated Privacy Policy.</p>

